// Fungsi untuk memfilter kota berdasarkan input
export function filterCities(searchTerm: string): string[] {
  if (!searchTerm.trim()) {
    return [];
  }

  const term = searchTerm.toLowerCase().trim();
  return indonesianCities
    .filter((city) => city.toLowerCase().includes(term))
    .slice(0, 10);
}
